alter table public.processed_operations
  add column if not exists tree_id uuid references public.trees(id) on delete set null,
  add column if not exists feed_sequence bigint generated by default as identity;

create unique index if not exists idx_processed_ops_feed_sequence
  on public.processed_operations(feed_sequence);
create index if not exists idx_processed_ops_tree_sequence
  on public.processed_operations(tree_id, feed_sequence);

update public.processed_operations op
set tree_id = t.id
from public.trees t
where op.tree_id is null and op.entity_type = 'tree' and op.entity_id = t.id;

update public.processed_operations op
set tree_id = p.tree_id
from public.persons p
where op.tree_id is null and op.entity_type = 'person' and op.entity_id = p.id;

update public.processed_operations op
set tree_id = r.tree_id
from public.relationships r
where op.tree_id is null and op.entity_type = 'relationship' and op.entity_id = r.id;

update public.processed_operations op
set tree_id = e.tree_id
from public.events e
where op.tree_id is null and op.entity_type = 'event' and op.entity_id = e.id;

update public.processed_operations op
set tree_id = p.tree_id
from public.photos p
where op.tree_id is null and op.entity_type = 'photo' and op.entity_id = p.id;

update public.processed_operations op
set tree_id = m.tree_id
from public.tree_memberships m
where op.tree_id is null and op.entity_type = 'treeMembership' and op.entity_id = m.id;

update public.processed_operations op
set tree_id = i.tree_id
from public.tree_invitations i
where op.tree_id is null and op.entity_type = 'treeInvitation' and op.entity_id = i.id;
